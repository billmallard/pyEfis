"""Conformance of pyEfis's route publisher with the route block fix-gateway's
synthetic tier flies (AER-4214, follow-up to SYN3, fix-gateway#56).

fix-gateway's sim gate checks the engine against an independent reference,
but the route block it loads comes from ``fixgw/sim/fplroute.py``, a
stand-in for this repo's publisher. If the two encode the same procedure
differently, that gate stays green while the box on glass flies a
different block. These tests publish each committed profile's procedure
through :class:`fixbridge.FixBridge` and diff every ``FPL{n}*`` slot and
``FPLS{k}*`` segment row against ``fplroute``'s output
(``fixtures/fplroute_blocks.json``, regenerated by ``fplroute_fixture.py``),
naming the first slot and field that differ.

What this does not cover yet: turning a coded procedure into a plan. pyEfis
has no assembler -- that is PA7/PA9 (AER-1606/AER-1608) -- so the plan
published here is fplroute's block read back through
:func:`fixbridge.route_to_plan`, the way a restarted display reads the bus.
That pins the wire encoding (flags, roles, segment rows, coded courses,
counts, writer order) but not the assembly choices fplroute documents
(transition/IF merge, CA slot position, which fix is the IAF). When PA7/PA9
land, :func:`_pyefis_plan` builds the plan from the procedures pack instead
and those choices come under test too.
"""

import json
import math
import os
from pathlib import Path

import pytest

from pyefis.flightplan import fixbridge
from tests.flightplan import fplroute_fixture
from tests.flightplan.test_fixbridge import _define, _define_all_fp1_keys

FIXTURE = json.loads(fplroute_fixture.FIXTURE.read_text())
PROFILES = sorted(FIXTURE["profiles"])

SLOT_FIELDS = [name for name, _, _ in fixbridge.SLOT_FIELDS]
SEGMENT_FIELDS = [name for name, _, _ in fixbridge.SEGMENT_FIELDS]

# fix-gateway doc/flightplan_keys.md defines FPLfCRS only for the legs that
# fly a coded course: the table row's list, plus FA ("continues on FPLfCRS
# past it like CA"). On every other leg the field is unspecified, the engine
# never reads it, and the two writers fill it differently (fplroute: the
# CIFP course if one is coded, else 0; pyEfis: the great-circle course into
# the fix plus MAGVAR), so it is not compared there.
COURSE_PTS = frozenset({"CF", "CA", "FA", "FC", "VA", "VM", "VI", "HM", "HF", "HA", "PI"})

# Keys checked by their own test below, because pyEfis does not write them.
NOT_WRITTEN_BY_PYEFIS = frozenset({"FPLAPRTYPE"})


def _reference(profile):
    return [tuple(w) for w in FIXTURE["profiles"][profile]["writes"]]


def _route_block(writes) -> fixbridge.RouteBlock:
    """fplroute's writes as the bus holds them, read the way
    :meth:`FixBridge.read_route` reads the bus."""
    db = dict(writes)
    slots = [fixbridge.RouteSlot(
        id=db[f"FPL{n}ID"], lat=db[f"FPL{n}LAT"], lon=db[f"FPL{n}LON"],
        type=fixbridge.FPLTYPE_TO_TYPE.get(db[f"FPL{n}TYPE"], "unknown"),
        role=fixbridge._flag_to_role(db[f"FPL{n}FLAGS"]), pt=db[f"FPL{n}PT"],
        crs=db[f"FPL{n}CRS"], dst=db[f"FPL{n}DST"], alt=db[f"FPL{n}ALT"],
        spd=db[f"FPL{n}SPD"], sgi=db[f"FPL{n}SGI"],
        flags=db[f"FPL{n}FLAGS"] & ~fixbridge._ROLE_BITS, ctr_lat=db[f"FPL{n}CTRLAT"],
        ctr_lon=db[f"FPL{n}CTRLON"], turn=db[f"FPL{n}TURN"])
        for n in range(1, db["FPLCOUNT"] + 1)]
    segments = [fixbridge.RouteSegment(
        kind=fixbridge.model.SEGMENT_KINDS[db[f"FPLS{k}KIND"]], ident=db[f"FPLS{k}ID"],
        entry=db[f"FPLS{k}ENT"], exit=db[f"FPLS{k}EXT"], first=db[f"FPLS{k}FIRST"],
        last=db[f"FPLS{k}LAST"])
        for k in range(1, db["FPLSEGCNT"] + 1)]
    return fixbridge.RouteBlock(name=db["FPLNAME"], seq=db["FPLSEQ"], waypoints=slots,
                                segments=segments, cycle=db["FPLDBCYC"])


def _pyefis_plan(profile):
    """The plan pyEfis would publish for *profile*'s procedure. Until PA7/PA9
    give pyEfis a procedure assembler, it is fplroute's block read back."""
    return fixbridge.route_to_plan(_route_block(_reference(profile)))


def _publish(fix, profile):
    """The ordered ``(key, value)`` writes ``FixBridge.publish`` makes for
    *profile* onto a gateway with an empty route block."""
    _define_all_fp1_keys(fix)
    _define(fix, "MAGVAR", "float", FIXTURE["profiles"][profile]["magvar_deg"])
    bridge = fixbridge.FixBridge(fix)
    assert bridge.available
    writes = []
    real_set = bridge._set

    def recording_set(key, value):
        writes.append((key, value))
        real_set(key, value)

    bridge._set = recording_set
    bridge.publish(_pyefis_plan(profile))
    return writes


def _same(a, b):
    if isinstance(a, float) or isinstance(b, float):
        return (not isinstance(a, str) and not isinstance(b, str)
                and math.isclose(a, b, rel_tol=0.0, abs_tol=1e-9))
    return a == b


def _first_difference(reference, published):
    """A description of the first compared key whose value differs, or
    None. Slots and segment rows come first, in slot order, then the
    block keys."""
    ref = dict(reference)
    got = dict(published)
    for n in range(1, ref["FPLCOUNT"] + 1):
        for name in SLOT_FIELDS:
            if name == "CRS" and ref[f"FPL{n}PT"] not in COURSE_PTS:
                continue
            key = f"FPL{n}{name}"
            if key not in got or not _same(ref[key], got[key]):
                return (f"slot {n} ({ref[f'FPL{n}ID'] or ref[f'FPL{n}PT']}) field {name}: "
                        f"fplroute {ref[key]!r}, pyEfis {got.get(key, '<not written>')!r}")
    for k in range(1, ref["FPLSEGCNT"] + 1):
        for name in SEGMENT_FIELDS:
            key = f"FPLS{k}{name}"
            if key not in got or not _same(ref[key], got[key]):
                return (f"segment {k} field {name}: "
                        f"fplroute {ref[key]!r}, pyEfis {got.get(key, '<not written>')!r}")
    for key in ("FPLSEGCNT", "FPLCOUNT", "FPLNAME", "FPLDBCYC", "FPLSEQ"):
        if key not in got or not _same(ref[key], got[key]):
            return f"{key}: fplroute {ref[key]!r}, pyEfis {got.get(key, '<not written>')!r}"
    return None


@pytest.mark.parametrize("profile", PROFILES)
def test_pyefis_publishes_the_block_the_sim_tier_flies(fix, profile):
    difference = _first_difference(_reference(profile), _publish(fix, profile))
    assert difference is None, f"{profile}: {difference}"


@pytest.mark.parametrize("profile", PROFILES)
def test_fplseq_is_the_last_write_after_every_route_key(fix, profile):
    """RS1 writer order: consumers act on the FPLSEQ change, so it has to
    follow every slot, row, count and name -- in both writers."""
    reference = _reference(profile)
    published = _publish(fix, profile)
    assert reference[-1][0] == "FPLSEQ"
    assert published[-1][0] == "FPLSEQ"
    route_keys = {k for k, _ in reference} - {"FPLSEQ"} - NOT_WRITTEN_BY_PYEFIS
    assert route_keys <= {k for k, _ in published[:-1]}


def test_the_differences_are_named_down_to_slot_and_field():
    """The diff has to point at the slot and field, not just fail."""
    reference = _reference(PROFILES[0])
    published = [(k, 0x00) if k == "FPL3FLAGS" else (k, v) for k, v in reference]
    assert _first_difference(reference, published).startswith("slot 3 (")
    assert "field FLAGS: fplroute 32, pyEfis 0" in _first_difference(reference, published)
    assert _first_difference(reference, reference) is None


@pytest.mark.xfail(strict=True, reason=(
    "pyEfis never writes FPLAPRTYPE; fix-gateway doc/flightplan_keys.md makes the editor "
    "its writer. Provenance only -- the engine stores and republishes it but flies "
    "nothing from it. PA9 (AER-1608) owns the approach type."))
@pytest.mark.parametrize("profile", PROFILES[:1])
def test_pyefis_writes_the_approach_type(fix, profile):
    got = dict(_publish(fix, profile))
    assert got.get("FPLAPRTYPE") == dict(_reference(profile))["FPLAPRTYPE"]


@pytest.mark.skipif(not os.environ.get("FIX_GATEWAY_SRC"),
                    reason="set FIX_GATEWAY_SRC to a fix-gateway checkout to check the fixture")
def test_the_fixture_matches_fix_gateway():
    """Regenerated from the fix-gateway checkout in FIX_GATEWAY_SRC, the
    blocks match what is committed here. On failure, rerun
    ``fplroute_fixture.py`` against that checkout and commit the result."""
    src = Path(os.environ["FIX_GATEWAY_SRC"])
    assert fplroute_fixture.generate(str(src)) == FIXTURE["profiles"]
