"""Conformance of pyEfis's route publisher with the route block fix-gateway's
synthetic tier flies (AER-4214, follow-up to SYN3, fix-gateway#56).

fix-gateway's sim gate checks the engine against an independent reference,
but the route block it loads comes from ``fixgw/sim/fplroute.py``, a
stand-in for this repo's publisher. If the two encode the same procedure
differently, that gate stays green while the box on glass flies a
different block. These tests publish each committed profile's procedure
through :class:`fixbridge.FixBridge` and diff every ``FPL{n}*`` slot and
``FPLS{k}*`` segment row against ``fplroute``'s output
(``fixtures/fplroute_blocks.json``, regenerated by ``fplroute_fixture.py``),
naming the first slot and field that differ.

For a profile that flies a procedure, the procedure is assembled the way
the PROC page loads it (PA7/PA9, AER-1606/AER-1608): :func:`proc_load.assemble`
over the pack rows makerplane-data's decoder writes from the CIFP file the
profile pins, then :func:`proc_load.insert` into the en-route part of the
route. So the assembly choices fplroute documents (transition/IF merge, CA
slot position, which fix is the IAF and the MAHP, the segment rows) are
under test as well as the wire encoding. The en-route part, and a profile
with no procedure, is fplroute's block read back through
:func:`fixbridge.route_to_plan`, the way a restarted display reads the bus:
pyEfis expands airways from its own pack, which these profiles do not carry.
"""

import json
import math
import os

import pytest

from pyefis.flightplan import fixbridge, geo, proc_load, procedures
from tests.flightplan import fplroute_fixture, ksba_procedures
from tests.flightplan.test_fixbridge import _define, _define_all_fp1_keys

FIXTURE = json.loads(fplroute_fixture.FIXTURE.read_text())
PROFILES = sorted(FIXTURE["profiles"])

SLOT_FIELDS = [name for name, _, _ in fixbridge.SLOT_FIELDS]
SEGMENT_FIELDS = [name for name, _, _ in fixbridge.SEGMENT_FIELDS]

# fix-gateway doc/flightplan_keys.md defines FPLfCRS only for the legs that
# fly a coded course: the table row's list, plus FA ("continues on FPLfCRS
# past it like CA"). On every other leg the field is unspecified, the engine
# never reads it, and the two writers fill it differently (fplroute: the
# CIFP course if one is coded, else 0; pyEfis: the great-circle course into
# the fix plus MAGVAR), so it is not compared there.
COURSE_PTS = frozenset({"CF", "CA", "FA", "FC", "VA", "VM", "VI", "HM", "HF", "HA", "PI"})

# Positions. makerplane-data's pack stores a fix's latitude and longitude to
# 8 decimals (about 1 mm), so an assembled fix is compared to 1e-7 deg. A
# slot with no fix (CA, VA, ...) is a point NO_FIX_POINT_NM along its coded
# course; pyEfis projects it on a sphere (geo.destination_point) and
# fplroute on WGS84, which lands about 10 m apart at 2 nm. The engine flies
# the leg along the coded course through the point, so it is compared to
# NO_FIX_TOLERANCE_NM.
POSITION_FIELDS = frozenset({"LAT", "LON", "CTRLAT", "CTRLON"})
POSITION_TOLERANCE_DEG = 1e-7
NO_FIX_TOLERANCE_NM = 0.01

FLOWN = [p for p in PROFILES if FIXTURE["profiles"][p]["procedure"]]


def _reference(profile):
    return [tuple(w) for w in FIXTURE["profiles"][profile]["writes"]]


def _route_block(writes) -> fixbridge.RouteBlock:
    """fplroute's writes as the bus holds them, read the way
    :meth:`FixBridge.read_route` reads the bus."""
    db = dict(writes)
    slots = [fixbridge.RouteSlot(
        id=db[f"FPL{n}ID"], lat=db[f"FPL{n}LAT"], lon=db[f"FPL{n}LON"],
        type=fixbridge.FPLTYPE_TO_TYPE.get(db[f"FPL{n}TYPE"], "unknown"),
        role=fixbridge._flag_to_role(db[f"FPL{n}FLAGS"]), pt=db[f"FPL{n}PT"],
        crs=db[f"FPL{n}CRS"], dst=db[f"FPL{n}DST"], alt=db[f"FPL{n}ALT"],
        spd=db[f"FPL{n}SPD"], sgi=db[f"FPL{n}SGI"],
        flags=db[f"FPL{n}FLAGS"] & ~fixbridge._ROLE_BITS, ctr_lat=db[f"FPL{n}CTRLAT"],
        ctr_lon=db[f"FPL{n}CTRLON"], turn=db[f"FPL{n}TURN"])
        for n in range(1, db["FPLCOUNT"] + 1)]
    segments = [fixbridge.RouteSegment(
        kind=fixbridge.model.SEGMENT_KINDS[db[f"FPLS{k}KIND"]], ident=db[f"FPLS{k}ID"],
        entry=db[f"FPLS{k}ENT"], exit=db[f"FPLS{k}EXT"], first=db[f"FPLS{k}FIRST"],
        last=db[f"FPLS{k}LAST"])
        for k in range(1, db["FPLSEGCNT"] + 1)]
    return fixbridge.RouteBlock(name=db["FPLNAME"], seq=db["FPLSEQ"], waypoints=slots,
                                segments=segments, cycle=db["FPLDBCYC"])


def _pack(profile, tmp_path) -> procedures.ProcedureIndex:
    rows = FIXTURE["profiles"][profile]["pack"]
    path = ksba_procedures.build(tmp_path / f"{profile}.db",
                                 *[[tuple(r) for r in rows[t]]
                                   for t in ("procedures", "transitions", "legs")])
    index = procedures.ProcedureIndex(path)
    assert index.ready
    return index


def _pyefis_plan(profile, tmp_path):
    """The plan pyEfis publishes for *profile*: the en-route part read back
    off fplroute's block, then the profile's procedure loaded from the pack."""
    entry = FIXTURE["profiles"][profile]
    plan = fixbridge.route_to_plan(_route_block(_reference(profile)))
    if entry["procedure"] is None:
        return plan
    proc = entry["procedure"]
    index = _pack(profile, tmp_path)
    approach = index.find(proc["airport"], "approach", proc["approach"])
    segments = proc_load.assemble(index, approach, proc["transition"],
                                  magvar=entry["magvar_deg"])
    proc_load.remove(plan, "approach")
    assert not proc_load.loaded(plan, "approach")
    proc_load.insert(plan, "approach", segments, proc["airport"])
    return plan


def _publish(fix, profile, tmp_path):
    """The ordered ``(key, value)`` writes ``FixBridge.publish`` makes for
    *profile* onto a gateway with an empty route block."""
    _define_all_fp1_keys(fix)
    _define(fix, "MAGVAR", "float", FIXTURE["profiles"][profile]["magvar_deg"])
    bridge = fixbridge.FixBridge(fix)
    assert bridge.available
    writes = []
    real_set = bridge._set

    def recording_set(key, value):
        writes.append((key, value))
        real_set(key, value)

    bridge._set = recording_set
    bridge.publish(_pyefis_plan(profile, tmp_path))
    return writes


def _same(a, b, tol=1e-9):
    if isinstance(a, float) or isinstance(b, float):
        return (not isinstance(a, str) and not isinstance(b, str)
                and math.isclose(a, b, rel_tol=0.0, abs_tol=tol))
    return a == b


def _slot_field_same(ref, got, n, name):
    key = f"FPL{n}{name}"
    if key not in got:
        return False
    if name in ("LAT", "LON") and not ref[f"FPL{n}ID"]:
        return (not isinstance(got[f"FPL{n}LAT"], str) and not isinstance(got[f"FPL{n}LON"], str)
                and geo.distance_nm(ref[f"FPL{n}LAT"], ref[f"FPL{n}LON"],
                                    got[f"FPL{n}LAT"], got[f"FPL{n}LON"]) <= NO_FIX_TOLERANCE_NM)
    return _same(ref[key], got[key],
                 POSITION_TOLERANCE_DEG if name in POSITION_FIELDS else 1e-9)


def _first_difference(reference, published):
    """A description of the first compared key whose value differs, or
    None. Slots and segment rows come first, in slot order, then the
    block keys."""
    ref = dict(reference)
    got = dict(published)
    for n in range(1, ref["FPLCOUNT"] + 1):
        for name in SLOT_FIELDS:
            if name == "CRS" and ref[f"FPL{n}PT"] not in COURSE_PTS:
                continue
            key = f"FPL{n}{name}"
            if not _slot_field_same(ref, got, n, name):
                return (f"slot {n} ({ref[f'FPL{n}ID'] or ref[f'FPL{n}PT']}) field {name}: "
                        f"fplroute {ref[key]!r}, pyEfis {got.get(key, '<not written>')!r}")
    for k in range(1, ref["FPLSEGCNT"] + 1):
        for name in SEGMENT_FIELDS:
            key = f"FPLS{k}{name}"
            if key not in got or not _same(ref[key], got[key]):
                return (f"segment {k} field {name}: "
                        f"fplroute {ref[key]!r}, pyEfis {got.get(key, '<not written>')!r}")
    for key in ("FPLSEGCNT", "FPLCOUNT", "FPLNAME", "FPLAPRTYPE", "FPLDBCYC", "FPLSEQ"):
        if key not in got or not _same(ref[key], got[key]):
            return f"{key}: fplroute {ref[key]!r}, pyEfis {got.get(key, '<not written>')!r}"
    return None


@pytest.mark.parametrize("profile", PROFILES)
def test_pyefis_publishes_the_block_the_sim_tier_flies(fix, profile, tmp_path):
    difference = _first_difference(_reference(profile), _publish(fix, profile, tmp_path))
    assert difference is None, f"{profile}: {difference}"


@pytest.mark.parametrize("profile", PROFILES)
def test_fplseq_is_the_last_write_after_every_route_key(fix, profile, tmp_path):
    """RS1 writer order: consumers act on the FPLSEQ change, so it has to
    follow every slot, row, count and name -- in both writers."""
    reference = _reference(profile)
    published = _publish(fix, profile, tmp_path)
    assert reference[-1][0] == "FPLSEQ"
    assert published[-1][0] == "FPLSEQ"
    route_keys = {k for k, _ in reference} - {"FPLSEQ"}
    assert route_keys <= {k for k, _ in published[:-1]}


def test_the_differences_are_named_down_to_slot_and_field():
    """The diff has to point at the slot and field, not just fail."""
    reference = _reference(FLOWN[0])
    published = [(k, 0x00) if k == "FPL3FLAGS" else (k, v) for k, v in reference]
    assert _first_difference(reference, published).startswith("slot 3 (")
    assert "field FLAGS: fplroute 32, pyEfis 0" in _first_difference(reference, published)
    assert _first_difference(reference, reference) is None


def test_positions_are_compared_to_their_tolerance():
    """A fix 1e-6 deg off is a difference; a no-fix slot is allowed its
    sphere/ellipsoid gap but not a leg's worth."""
    reference = _reference(FLOWN[0])
    ref = dict(reference)
    n = next(i for i in range(1, ref["FPLCOUNT"] + 1) if ref[f"FPL{i}ID"])
    moved = [(k, v + 1e-6) if k == f"FPL{n}LAT" else (k, v) for k, v in reference]
    assert f"slot {n} ({ref[f'FPL{n}ID']}) field LAT" in _first_difference(reference, moved)
    c = next(i for i in range(1, ref["FPLCOUNT"] + 1) if not ref[f"FPL{i}ID"])
    near = [(k, v + 0.0001) if k == f"FPL{c}LAT" else (k, v) for k, v in reference]
    assert _first_difference(reference, near) is None
    far = [(k, v + 0.001) if k == f"FPL{c}LAT" else (k, v) for k, v in reference]
    assert f"slot {c} (CA) field LAT" in _first_difference(reference, far)


@pytest.mark.parametrize("profile", PROFILES)
def test_pyefis_writes_the_approach_type(fix, profile, tmp_path):
    """PA9 (AER-1608): the editor is FPLAPRTYPE's writer (fix-gateway
    doc/flightplan_keys.md), and writes what fplroute writes."""
    got = dict(_publish(fix, profile, tmp_path))
    assert got.get("FPLAPRTYPE") == dict(_reference(profile))["FPLAPRTYPE"]


def test_the_procedures_are_assembled_not_read_back():
    """Every profile that flies a procedure carries the pack rows it is
    assembled from, so the tests above do not compare fplroute with itself."""
    assert FLOWN
    assert all(FIXTURE["profiles"][p]["pack"]["legs"] for p in FLOWN)


@pytest.mark.skipif(not (os.environ.get("FIX_GATEWAY_SRC") and os.environ.get("MAKERPLANE_DATA_SRC")),
                    reason="set FIX_GATEWAY_SRC and MAKERPLANE_DATA_SRC to the two checkouts "
                           "to check the fixture")
def test_the_fixture_matches_fix_gateway():
    """Regenerated from the checkouts in FIX_GATEWAY_SRC and
    MAKERPLANE_DATA_SRC, the blocks and pack rows match what is committed
    here. On failure, rerun ``fplroute_fixture.py`` against them and commit
    the result."""
    generated = fplroute_fixture.generate(os.environ["FIX_GATEWAY_SRC"],
                                          os.environ["MAKERPLANE_DATA_SRC"])
    assert json.loads(json.dumps(generated)) == FIXTURE["profiles"]
