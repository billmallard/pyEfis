"""Build the AER-6052 private pyEfis config tree.

    python3 mkconfig_pyefis.py <branch src/pyefis/config> <live managed.yaml> <out> <netfix port>

The branch's shipped tree, pointed at the private gateway, with one screen:
the bench's live PFD virtual_vfr options (SVS on) with fd_style single_cue on
the left, and a plain atitude_indicator with fd_style cross_pointer plus the
AFC3 autopilot panel on the right. Nothing here touches the live config."""
import os, shutil, sys
import yaml

src, live, out, port = sys.argv[1:5]
shutil.rmtree(out, ignore_errors=True)
shutil.copytree(src, out)


def sub(p, old, new):
    s = open(p).read()
    assert s.count(old) == 1, (p, old)
    open(p, "w").write(s.replace(old, new))


m = os.path.join(out, "main/default.yaml")
sub(m, "FixPort: 3490", "FixPort: %s" % port)
sub(m, "defaultScreen: PFD", "defaultScreen: AFC5")

pfd = yaml.safe_load(open(live))
vvfr = next(i for i in pfd["PFD"]["instruments"] if i["type"] == "virtual_vfr")
opts = dict(vvfr["options"])
opts["fd_style"] = "single_cue"
screen = {"AFC5": {
    "module": "pyefis.screens.screenbuilder",
    "title": "AFC5 bench",
    "layout": {"rows": 110, "columns": 200},
    "instruments": [
        {"type": "virtual_vfr", "row": 0, "column": 0,
         "span": {"rows": 110, "columns": 110}, "options": opts},
        {"type": "atitude_indicator", "row": 0, "column": 115,
         "span": {"rows": 64, "columns": 80},
         "options": {"fd_style": "cross_pointer"}},
        {"type": "autopilot_panel", "row": 70, "column": 112,
         "span": {"rows": 38, "columns": 86}, "options": {"layout": "full"}},
    ]}}
with open(os.path.join(out, "screens/aer6052.yaml"), "w") as f:
    f.write("# AER-6052 bench session screen (generated by mkconfig_pyefis.py)\n")
    yaml.safe_dump(screen, f, sort_keys=False)
with open(os.path.join(out, "screens/aer6052_list.yaml"), "w") as f:
    f.write("include:\n  - SCREEN_AFC5\n")
with open(os.path.join(out, "preferences.yaml.custom"), "w") as f:
    f.write("enabled:\n  AUTO_START: true\n"
            "includes:\n  SCREENS_CONFIG: screens/aer6052_list.yaml\n"
            "  SCREEN_AFC5: screens/aer6052.yaml\n")
print("pyefis config ok:", out, "port", port)
