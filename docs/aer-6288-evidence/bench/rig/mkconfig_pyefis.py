"""Build the AER-6288 private pyEfis config tree.

    python3 mkconfig_pyefis.py <dev src/pyefis/config> <live managed.yaml> <out> <netfix port>

pyEfis dev's shipped tree, pointed at the private gateway, with one screen:
the bench's live PFD (virtual_vfr, airspeed and altimeter tapes, VS trend
tape, HSI, wind) with its options unchanged, plus the AFC4 cues it does not
carry yet: `ap_annunciator` across the top of the attitude display, a
`vsi_pfd` (the VSSEL bug) and the AFC3 autopilot panel where the live screen
has its tab section. The tapes keep their shipped cue defaults (IASSEL box and
bug, ALTSEL box with the capture look). Nothing here touches the live config.
Writes strip_geometry.json beside the tree: the strip's pixel rectangle on a
1920x1080 window, from pyEfis's own layout code, for score.py."""
import json
import os
import shutil
import sys

import yaml

src, live, out, port = sys.argv[1:5]
shutil.rmtree(out, ignore_errors=True)
shutil.copytree(src, out)


def sub(p, old, new):
    s = open(p).read()
    assert s.count(old) == 1, (p, old)
    open(p, "w").write(s.replace(old, new))


m = os.path.join(out, "main/default.yaml")
sub(m, "FixPort: 3490", "FixPort: %s" % port)
sub(m, "defaultScreen: PFD", "defaultScreen: AFC4")

pfd = yaml.safe_load(open(live))["PFD"]
keep = [i for i in pfd["instruments"] if i["type"] != "tab_section"]
assert len(keep) == len(pfd["instruments"]) - 1, [i["type"] for i in pfd["instruments"]]
assert {i["type"] for i in keep} >= {"virtual_vfr", "airspeed_tape", "altimeter_tape"}
strip = {"type": "ap_annunciator", "row": 0, "column": 0,
         "span": {"rows": 6, "columns": 130}, "options": {}}
extra = [
    strip,
    {"type": "vsi_pfd", "row": 6, "column": 133,
     "span": {"rows": 60, "columns": 14}, "options": {}},
    {"type": "autopilot_panel", "row": 70, "column": 132,
     "span": {"rows": 38, "columns": 66}, "options": {"layout": "full"}},
]
screen = {"AFC4": {
    "module": "pyefis.screens.screenbuilder",
    "title": "AFC4 bench",
    "layout": pfd["layout"],
    "instruments": keep + extra}}
with open(os.path.join(out, "screens/aer6288.yaml"), "w") as f:
    f.write("# AER-6288 bench session screen (generated by mkconfig_pyefis.py)\n")
    yaml.safe_dump(screen, f, sort_keys=False)
with open(os.path.join(out, "screens/aer6288_list.yaml"), "w") as f:
    f.write("include:\n  - SCREEN_AFC4\n")
with open(os.path.join(out, "preferences.yaml.custom"), "w") as f:
    f.write("enabled:\n  AUTO_START: true\n"
            "includes:\n  SCREENS_CONFIG: screens/aer6288_list.yaml\n"
            "  SCREEN_AFC4: screens/aer6288.yaml\n")

sys.path.insert(0, os.path.join(src, "..", ".."))
from pyefis.screens import screenbuilder_layout as sl
g = sl.get_instrument_geometry(pfd["layout"], 1920, 1080, strip, False)
geo = {k: g[k] for k in ("x", "y", "render_width", "render_height")}
with open(os.path.join(os.path.dirname(out.rstrip("/")), "strip_geometry.json"), "w") as f:
    json.dump(geo, f)
print("pyefis config ok:", out, "port", port, "strip", geo,
      "instruments", [i["type"] for i in screen["AFC4"]["instruments"]])
